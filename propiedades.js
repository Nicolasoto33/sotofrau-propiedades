/* =====================================================
   GENERAR TARJETAS EN INICIO
===================================================== */

function cargarPropiedades() {

  const contenedor =
    document.getElementById(
      "propertyGrid"
    );

  if (!contenedor) {

    return;

  }


  contenedor.innerHTML = "";


  /*
    FILTRAR SOLO LAS PROPIEDADES PUBLICADAS
    Y ORDENAR AUTOMÁTICAMENTE:
    
    1. DISPONIBLES PRIMERO
    2. DENTRO DE CADA GRUPO, ID MÁS ALTO PRIMERO
    
    De esta forma, cuando agregues una nueva
    propiedad disponible con un ID mayor,
    aparecerá automáticamente arriba.
  */

  const propiedadesPublicadas =
    propiedades
      .filter(
        function(propiedad) {

          return propiedad.publicada === true;

        }
      )
      .sort(
        function(a, b) {

          const prioridadA =
            a.estado === "disponible"
              ? 0
              : 1;


          const prioridadB =
            b.estado === "disponible"
              ? 0
              : 1;


          /*
            Primero se comparan los estados.
            0 = disponible
            1 = gestionada / arrendada / vendida
          */

          if (
            prioridadA !== prioridadB
          ) {

            return prioridadA -
              prioridadB;

          }


          /*
            Si ambas tienen el mismo estado,
            la de ID más alto aparece primero.
          */

          return b.id -
            a.id;

        }
      );


  propiedadesPublicadas.forEach(
    function(propiedad) {

      const tarjeta =
        document.createElement(
          "article"
        );


      tarjeta.className =
        "property-card";


      tarjeta.dataset.operation =
        propiedad.operacion.toLowerCase();


      tarjeta.dataset.status =
        propiedad.estado.toLowerCase();


      let claseEstado =
        "status-arrendada";


      if (
        propiedad.estado.toLowerCase() ===
        "disponible"
      ) {

        claseEstado =
          "status-disponible";

      }


      if (
        propiedad.estado.toLowerCase() ===
        "vendida"
      ) {

        claseEstado =
          "status-vendida";

      }


      const caracteristicas =
        propiedad.caracteristicas
          .map(
            function(caracteristica) {

              return `
                <span>
                  ${caracteristica}
                </span>
              `;

            }
          )
          .join("");


      const enlace =
        "propiedad.html?id=" +
        propiedad.id;


      tarjeta.innerHTML = `

        <div class="property-image">

          <span
            class="status ${claseEstado}"
          >
            ${propiedad.estadoTexto}
          </span>


          <img
            src="${propiedad.fotos[0]}"
            alt="${propiedad.titulo}"
            loading="lazy"
          >

        </div>


        <div class="property-content">

          <div class="operation">
            ${propiedad.operacion}
          </div>


          <h3>
            ${propiedad.titulo}
          </h3>


          <div class="location">
            ${propiedad.ubicacion}
          </div>


          <div class="price">
            ${propiedad.precio}
          </div>


          <div class="features">

            ${caracteristicas}

          </div>


          <a
            href="${enlace}"
            class="property-button"
          >
            Ver propiedad
          </a>

        </div>

      `;


      contenedor.appendChild(
        tarjeta
      );

    }
  );

}


/* =====================================================
   FILTROS
===================================================== */

function filtrar(
  tipo,
  boton
) {

  const tarjetas =
    document.querySelectorAll(
      ".property-card"
    );


  const botones =
    document.querySelectorAll(
      ".filter"
    );


  botones.forEach(
    function(b) {

      b.classList.remove(
        "active"
      );

    }
  );


  if (boton) {

    boton.classList.add(
      "active"
    );

  }


  tarjetas.forEach(
    function(tarjeta) {

      const operacion =
        tarjeta.dataset.operation;


      const estado =
        tarjeta.dataset.status;


      let mostrar =
        false;


      if (
        tipo === "todas"
      ) {

        mostrar = true;

      }


      if (
        tipo === "venta" &&
        operacion === "venta"
      ) {

        mostrar = true;

      }


      if (
        tipo === "arriendo" &&
        operacion === "arriendo"
      ) {

        mostrar = true;

      }


      if (
        tipo === "disponible" &&
        estado === "disponible"
      ) {

        mostrar = true;

      }


      if (
        tipo === "gestionada" &&
        estado === "gestionada"
      ) {

        mostrar = true;

      }


      tarjeta.classList.toggle(
        "hidden",
        !mostrar
      );

    }
  );

}



